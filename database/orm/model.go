package orm

import (
	"context"
	"fmt"
	"reflect"
	"time"
)

func target[T any](model *T) (*meta, reflect.Value, error) {
	m, err := metaOf(reflect.TypeFor[T]())
	if err != nil {
		return nil, reflect.Value{}, err
	}
	if model == nil {
		return nil, reflect.Value{}, fmt.Errorf("orm: model must not be nil")
	}
	return m, reflect.ValueOf(model).Elem(), nil
}

// keyed returns the model's primary key value, or ErrMissingPrimaryKey when it is zero.
func keyed(m *meta, v reflect.Value) (any, error) {
	pk := v.FieldByIndex(m.pk.index)
	if pk.IsZero() {
		return nil, ErrMissingPrimaryKey
	}
	return pk.Interface(), nil
}

// Find returns the model with primary key id or ErrNotFound.
func Find[T any](ctx context.Context, db DB, id any) (*T, error) {
	return Query[T](db).Find(ctx, id)
}

// Create inserts model. A zero integer primary key is generated by the
// database and written back; created_at and updated_at are set when zero.
func Create[T any](ctx context.Context, db DB, model *T) error {
	m, v, err := target(model)
	if err != nil {
		return err
	}
	if db == nil {
		return fmt.Errorf("orm: connection is required")
	}
	t := now()
	for _, f := range []*field{m.createdAt, m.updatedAt} {
		if f != nil && v.FieldByIndex(f.index).IsZero() {
			setTime(v.FieldByIndex(f.index), &t)
		}
	}
	pk := v.FieldByIndex(m.pk.index)
	generate := m.autoPK && pk.IsZero()
	values := map[string]any{}
	for _, f := range m.fields {
		if f != m.pk || !generate {
			values[f.column] = v.FieldByIndex(f.index).Interface()
		}
	}
	q := db.Table(m.table)
	if !generate {
		if _, err := q.InsertContext(ctx, values); err != nil {
			return fmt.Errorf("orm: create %s: %w", m.table, err)
		}
		return nil
	}
	id, err := q.InsertGetID(ctx, values, m.pk.column)
	if err != nil {
		return fmt.Errorf("orm: create %s: %w", m.table, err)
	}
	if pk.CanInt() {
		pk.SetInt(id)
	} else {
		pk.SetUint(uint64(id))
	}
	return nil
}

// Save updates every column of model except the primary key, created_at and
// deleted_at, and sets updated_at.
func Save[T any](ctx context.Context, db DB, model *T) error {
	m, v, err := target(model)
	if err != nil {
		return err
	}
	id, err := keyed(m, v)
	if err != nil {
		return err
	}
	if m.updatedAt != nil {
		t := now()
		setTime(v.FieldByIndex(m.updatedAt.index), &t)
	}
	values := map[string]any{}
	for _, f := range m.fields {
		if f != m.pk && f != m.createdAt && f != m.deletedAt {
			values[f.column] = v.FieldByIndex(f.index).Interface()
		}
	}
	if len(values) == 0 {
		return nil
	}
	if _, err := db.Table(m.table).Where(m.pk.column, "=", id).UpdateContext(ctx, values); err != nil {
		return fmt.Errorf("orm: save %s: %w", m.table, err)
	}
	return nil
}

// Delete soft-deletes model when it has a deleted_at field and removes it otherwise.
func Delete[T any](ctx context.Context, db DB, model *T) error {
	m, v, err := target(model)
	if err != nil {
		return err
	}
	if m.deletedAt == nil {
		return ForceDelete(ctx, db, model)
	}
	return setDeletedAt(ctx, db, m, v, "delete", true)
}

// Restore clears model's deleted_at.
func Restore[T any](ctx context.Context, db DB, model *T) error {
	m, v, err := target(model)
	if err != nil {
		return err
	}
	if m.deletedAt == nil {
		return fmt.Errorf("orm: %s does not support soft deletes", m.typ)
	}
	return setDeletedAt(ctx, db, m, v, "restore", false)
}

func setDeletedAt(ctx context.Context, db DB, m *meta, v reflect.Value, operation string, deleted bool) error {
	id, err := keyed(m, v)
	if err != nil {
		return err
	}
	var t *time.Time
	var value any
	if deleted {
		stamp := now()
		t, value = &stamp, stamp
	}
	if _, err := db.Table(m.table).Where(m.pk.column, "=", id).UpdateContext(ctx, map[string]any{m.deletedAt.column: value}); err != nil {
		return fmt.Errorf("orm: %s %s: %w", operation, m.table, err)
	}
	setTime(v.FieldByIndex(m.deletedAt.index), t)
	return nil
}

// ForceDelete removes model's row even when it supports soft deletes.
func ForceDelete[T any](ctx context.Context, db DB, model *T) error {
	m, v, err := target(model)
	if err != nil {
		return err
	}
	id, err := keyed(m, v)
	if err != nil {
		return err
	}
	if _, err := db.Table(m.table).Where(m.pk.column, "=", id).DeleteContext(ctx); err != nil {
		return fmt.Errorf("orm: delete %s: %w", m.table, err)
	}
	return nil
}

// Load loads relations onto one model, e.g. Load(ctx, db, &user, "Posts").
func Load[T any](ctx context.Context, db DB, model *T, relations ...string) error {
	m, v, err := target(model)
	if err != nil {
		return err
	}
	return load(ctx, db, m, []reflect.Value{v}, relations)
}

// LoadAll loads relations onto every model in models with one query per relation.
func LoadAll[T any](ctx context.Context, db DB, models []T, relations ...string) error {
	m, err := metaOf(reflect.TypeFor[T]())
	if err != nil || len(models) == 0 {
		return err
	}
	owners := make([]reflect.Value, len(models))
	for i := range models {
		owners[i] = reflect.ValueOf(&models[i]).Elem()
	}
	return load(ctx, db, m, owners, relations)
}
