package schema

import (
	"crypto/sha256"
	"fmt"
	"strconv"
	"strings"
	"time"
)

type Compiler interface {
	CompileCreate(*Blueprint) ([]string, error)
	CompileAlter(*Blueprint) ([]string, error)
	Quote(string) string
}
type SQLCompiler struct{ Dialect string }

func NewCompiler(dialect string) (Compiler, error) {
	switch dialect {
	case "sqlite", "postgres", "mysql":
		return SQLCompiler{Dialect: dialect}, nil
	default:
		return nil, fmt.Errorf("schema: unsupported dialect %q", dialect)
	}
}
func (c SQLCompiler) Quote(name string) string {
	quote := "\""
	if c.Dialect == "mysql" {
		quote = "`"
	}
	return quote + strings.ReplaceAll(name, quote, quote+quote) + quote
}
func (c SQLCompiler) name(name string) error {
	limit := 63
	if c.Dialect == "mysql" {
		limit = 64
	}
	if name == "" || strings.ContainsRune(name, 0) {
		return fmt.Errorf("schema: invalid identifier %q", name)
	}
	if c.Dialect != "sqlite" && len(name) > limit {
		return fmt.Errorf("schema: identifier %q exceeds %d bytes", name, limit)
	}
	return nil
}
func (c SQLCompiler) autoName(table string, columns []string, suffix string) string {
	name := table + "_" + strings.Join(columns, "_") + "_" + suffix
	if len(name) > 60 {
		hash := fmt.Sprintf("%x", sha256.Sum256([]byte(name)))
		name = name[:47] + "_" + hash[:12]
	}
	return name
}
func (c SQLCompiler) columns(names []string) (string, error) {
	if len(names) == 0 {
		return "", fmt.Errorf("schema: column list is empty")
	}
	result := make([]string, len(names))
	for i, name := range names {
		if err := c.name(name); err != nil {
			return "", err
		}
		result[i] = c.Quote(name)
	}
	return strings.Join(result, ", "), nil
}
func (c SQLCompiler) column(col *Column) (string, error) {
	if err := c.name(col.Name); err != nil {
		return "", err
	}
	kind := ""
	switch col.Type {
	case "string":
		if col.Length < 1 || col.Length > 65535 {
			return "", fmt.Errorf("schema: invalid string length")
		}
		kind = fmt.Sprintf("VARCHAR(%d)", col.Length)
	case "text":
		kind = "TEXT"
	case "integer":
		kind = "INTEGER"
	case "bigint":
		kind = "BIGINT"
	case "boolean":
		kind = "BOOLEAN"
	case "float":
		kind = "DOUBLE PRECISION"
		if c.Dialect == "sqlite" {
			kind = "REAL"
		}
	case "decimal":
		if col.Precision < 1 || col.Precision > 65 || col.Scale < 0 || col.Scale > col.Precision {
			return "", fmt.Errorf("schema: invalid decimal precision/scale")
		}
		kind = fmt.Sprintf("DECIMAL(%d,%d)", col.Precision, col.Scale)
	case "date":
		kind = "DATE"
	case "datetime", "timestamp":
		kind = "TIMESTAMP"
		if c.Dialect == "mysql" {
			kind = "DATETIME"
		}
	case "json":
		kind = "JSON"
		if c.Dialect == "postgres" {
			kind = "JSONB"
		}
		if c.Dialect == "sqlite" {
			kind = "TEXT"
		}
	case "uuid":
		kind = "UUID"
		if c.Dialect != "postgres" {
			kind = "CHAR(36)"
		}
	case "binary":
		kind = "BLOB"
		if c.Dialect == "postgres" {
			kind = "BYTEA"
		}
	default:
		return "", fmt.Errorf("schema: unsupported column type %q for %s", col.Type, c.Dialect)
	}
	if col.IsUnsigned {
		if c.Dialect != "mysql" {
			return "", fmt.Errorf("schema: unsigned is unsupported for %s", c.Dialect)
		}
		if col.Type != "integer" && col.Type != "bigint" && col.Type != "decimal" && col.Type != "float" {
			return "", fmt.Errorf("schema: unsigned requires numeric column")
		}
		kind += " UNSIGNED"
	}
	if col.IsAutoIncrement {
		if col.Type != "integer" && col.Type != "bigint" {
			return "", fmt.Errorf("schema: auto increment requires integer")
		}
		switch c.Dialect {
		case "sqlite":
			if !col.IsPrimary {
				return "", fmt.Errorf("schema: sqlite autoincrement requires primary key")
			}
			kind = "INTEGER"
		case "postgres":
			kind += " GENERATED BY DEFAULT AS IDENTITY"
		case "mysql":
			kind += " AUTO_INCREMENT"
		}
	}
	sql := c.Quote(col.Name) + " " + kind
	if col.IsPrimary {
		sql += " PRIMARY KEY"
	}
	if col.IsAutoIncrement && c.Dialect == "sqlite" {
		sql += " AUTOINCREMENT"
	}
	if !col.IsNullable {
		sql += " NOT NULL"
	}
	if col.IsUnique {
		sql += " UNIQUE"
	}
	if col.HasDefault {
		value, err := c.literal(col.DefaultValue)
		if err != nil {
			return "", err
		}
		sql += " DEFAULT " + value
	}
	return sql, nil
}
func (c SQLCompiler) literal(value any) (string, error) {
	switch v := value.(type) {
	case nil:
		return "NULL", nil
	case string:
		return "'" + strings.ReplaceAll(v, "'", "''") + "'", nil
	case bool:
		if v {
			return "TRUE", nil
		}
		return "FALSE", nil
	case int:
		return strconv.Itoa(v), nil
	case int8, int16, int32, int64, uint, uint8, uint16, uint32, uint64:
		return fmt.Sprint(v), nil
	case float32, float64:
		s := fmt.Sprint(v)
		if s == "NaN" || strings.Contains(s, "Inf") {
			return "", fmt.Errorf("schema: invalid numeric default")
		}
		return s, nil
	case time.Time:
		return "'" + v.UTC().Format("2006-01-02 15:04:05") + "'", nil
	case Expression:
		if v == CurrentTimestamp {
			return string(v), nil
		}
		return "", fmt.Errorf("schema: unsupported default expression")
	default:
		return "", fmt.Errorf("schema: unsupported default type %T", value)
	}
}
func (c SQLCompiler) foreign(table string, f *ForeignKey) (string, error) {
	if len(f.Columns) != len(f.TargetColumns) {
		return "", fmt.Errorf("schema: foreign key column counts differ")
	}
	columns, err := c.columns(f.Columns)
	if err != nil {
		return "", err
	}
	targets, err := c.columns(f.TargetColumns)
	if err != nil {
		return "", err
	}
	if err = c.name(f.TargetTable); err != nil {
		return "", err
	}
	name := f.Name
	if name == "" {
		name = c.autoName(table, f.Columns, "foreign")
	}
	if err = c.name(name); err != nil {
		return "", err
	}
	sql := "CONSTRAINT " + c.Quote(name) + " FOREIGN KEY (" + columns + ") REFERENCES " + c.Quote(f.TargetTable) + " (" + targets + ")"
	for _, action := range []struct{ kind, value string }{{"DELETE", f.DeleteAction}, {"UPDATE", f.UpdateAction}} {
		if action.value == "" {
			continue
		}
		v := strings.ToUpper(action.value)
		switch v {
		case "CASCADE", "RESTRICT", "SET NULL", "NO ACTION", "SET DEFAULT":
		default:
			return "", fmt.Errorf("schema: invalid foreign key action %q", action.value)
		}
		if c.Dialect == "mysql" && v == "SET DEFAULT" {
			return "", fmt.Errorf("schema: mysql does not support SET DEFAULT")
		}
		sql += " ON " + action.kind + " " + v
	}
	return sql, nil
}
func (c SQLCompiler) index(table string, index *Index) (string, error) {
	columns, err := c.columns(index.Columns)
	if err != nil {
		return "", err
	}
	if index.Primary {
		return "", fmt.Errorf("schema: primary index must be a table constraint")
	}
	name := index.Name
	if name == "" {
		suffix := "index"
		if index.Unique {
			suffix = "unique"
		}
		name = c.autoName(table, index.Columns, suffix)
	}
	if err = c.name(name); err != nil {
		return "", err
	}
	prefix := "CREATE INDEX "
	if index.Unique {
		prefix = "CREATE UNIQUE INDEX "
	}
	return prefix + c.Quote(name) + " ON " + c.Quote(table) + " (" + columns + ")", nil
}
func (c SQLCompiler) CompileCreate(b *Blueprint) ([]string, error) {
	if _, err := NewCompiler(c.Dialect); err != nil {
		return nil, err
	}
	if err := c.name(b.Table); err != nil {
		return nil, err
	}
	if len(b.Columns) == 0 {
		return nil, fmt.Errorf("schema: table requires columns")
	}
	parts := []string{}
	seen := map[string]bool{}
	primary := 0
	for _, col := range b.Columns {
		if seen[col.Name] {
			return nil, fmt.Errorf("schema: duplicate column %q", col.Name)
		}
		seen[col.Name] = true
		if col.IsPrimary {
			primary++
		}
		sql, err := c.column(col)
		if err != nil {
			return nil, err
		}
		parts = append(parts, sql)
	}
	for _, index := range b.Indexes {
		if index.Primary {
			primary++
			columns, err := c.columns(index.Columns)
			if err != nil {
				return nil, err
			}
			parts = append(parts, "PRIMARY KEY ("+columns+")")
		}
	}
	if primary > 1 {
		return nil, fmt.Errorf("schema: multiple primary keys")
	}
	for _, f := range b.ForeignKeys {
		sql, err := c.foreign(b.Table, f)
		if err != nil {
			return nil, err
		}
		parts = append(parts, sql)
	}
	for _, index := range b.Indexes {
		for _, name := range index.Columns {
			if !seen[name] {
				return nil, fmt.Errorf("schema: index column %q not found", name)
			}
		}
	}
	for _, foreign := range b.ForeignKeys {
		for _, name := range foreign.Columns {
			if !seen[name] {
				return nil, fmt.Errorf("schema: foreign key column %q not found", name)
			}
		}
	}
	result := []string{"CREATE TABLE " + c.Quote(b.Table) + " (" + strings.Join(parts, ", ") + ")"}
	for _, index := range b.Indexes {
		if !index.Primary {
			sql, err := c.index(b.Table, index)
			if err != nil {
				return nil, err
			}
			result = append(result, sql)
		}
	}
	return result, nil
}
func (c SQLCompiler) CompileAlter(b *Blueprint) ([]string, error) {
	if _, err := NewCompiler(c.Dialect); err != nil {
		return nil, err
	}
	if err := c.name(b.Table); err != nil {
		return nil, err
	}
	prefix := "ALTER TABLE " + c.Quote(b.Table) + " "
	result := []string{}
	for _, name := range b.DroppedIndexes {
		if err := c.name(name); err != nil {
			return nil, err
		}
		sql := "DROP INDEX " + c.Quote(name)
		if c.Dialect == "mysql" {
			sql += " ON " + c.Quote(b.Table)
		}
		result = append(result, sql)
	}
	for _, name := range b.DroppedForeignKeys {
		if err := c.name(name); err != nil {
			return nil, err
		}
		if c.Dialect == "sqlite" {
			return nil, fmt.Errorf("schema: sqlite foreign key changes require table rebuild")
		}
		operation := "DROP CONSTRAINT "
		if c.Dialect == "mysql" {
			operation = "DROP FOREIGN KEY "
		}
		result = append(result, prefix+operation+c.Quote(name))
	}
	for _, col := range b.Columns {
		definition, err := c.column(col)
		if err != nil {
			return nil, err
		}
		if !col.Changing {
			result = append(result, prefix+"ADD COLUMN "+definition)
			continue
		}
		switch c.Dialect {
		case "sqlite":
			return nil, fmt.Errorf("schema: sqlite column change requires table rebuild")
		case "mysql":
			result = append(result, prefix+"MODIFY COLUMN "+definition)
		case "postgres":
			if col.IsPrimary || col.IsAutoIncrement {
				return nil, fmt.Errorf("schema: changing postgres identity/primary keys requires an explicit constraint migration")
			}
			copy := *col
			copy.Name = "_type"
			copy.IsUnique = false
			copy.IsPrimary = false
			copy.IsAutoIncrement = false
			copy.IsNullable = true
			copy.HasDefault = false
			typeDef, err := c.column(&copy)
			if err != nil {
				return nil, err
			}
			kind := strings.TrimPrefix(typeDef, c.Quote("_type")+" ")
			result = append(result, prefix+"ALTER COLUMN "+c.Quote(col.Name)+" TYPE "+kind)
			null := "SET NOT NULL"
			if col.IsNullable {
				null = "DROP NOT NULL"
			}
			result = append(result, prefix+"ALTER COLUMN "+c.Quote(col.Name)+" "+null)
			if col.HasDefault {
				v, err := c.literal(col.DefaultValue)
				if err != nil {
					return nil, err
				}
				result = append(result, prefix+"ALTER COLUMN "+c.Quote(col.Name)+" SET DEFAULT "+v)
			}
			if col.IsUnique {
				statement, e := c.index(b.Table, &Index{Columns: []string{col.Name}, Unique: true})
				if e != nil {
					return nil, e
				}
				result = append(result, statement)
			}
		}
	}
	for _, name := range b.DroppedColumns {
		if err := c.name(name); err != nil {
			return nil, err
		}
		result = append(result, prefix+"DROP COLUMN "+c.Quote(name))
	}
	for _, rename := range b.RenamedColumns {
		if err := c.name(rename.From); err != nil {
			return nil, err
		}
		if err := c.name(rename.To); err != nil {
			return nil, err
		}
		result = append(result, prefix+"RENAME COLUMN "+c.Quote(rename.From)+" TO "+c.Quote(rename.To))
	}
	for _, index := range b.Indexes {
		if index.Primary {
			columns, err := c.columns(index.Columns)
			if err != nil {
				return nil, err
			}
			if c.Dialect == "sqlite" {
				return nil, fmt.Errorf("schema: sqlite primary key changes require table rebuild")
			}
			result = append(result, prefix+"ADD PRIMARY KEY ("+columns+")")
		} else {
			sql, err := c.index(b.Table, index)
			if err != nil {
				return nil, err
			}
			result = append(result, sql)
		}
	}
	for _, f := range b.ForeignKeys {
		if c.Dialect == "sqlite" {
			return nil, fmt.Errorf("schema: sqlite foreign key changes require table rebuild")
		}
		sql, err := c.foreign(b.Table, f)
		if err != nil {
			return nil, err
		}
		result = append(result, prefix+"ADD "+sql)
	}
	return result, nil
}
