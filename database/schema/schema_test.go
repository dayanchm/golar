func TestRebuildPreservesSequence(t *testing.T) {
	db, err := database.Connect(database.Config{Driver: "sqlite", Database: filepath.Join(t.TempDir(), "test.db")})
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	s := schema.New(db.DB, "sqlite")
	if err = s.Create("users", func(b *schema.Blueprint) { b.ID(); b.String("name", 100) }); err != nil {
		t.Fatal(err)
	}
	if _, err = db.Exec("INSERT INTO users (id,name) VALUES (50,'removed')"); err != nil {
		t.Fatal(err)
	}
	if _, err = db.Exec("DELETE FROM users"); err != nil {
		t.Fatal(err)
	}
	if err = s.Table("users", func(b *schema.Blueprint) { b.String("name", 255).Change() }); err != nil {
		t.Fatal(err)
	}
	result, err := db.Exec("INSERT INTO users (name) VALUES ('new')")
	if err != nil {
		t.Fatal(err)
	}
	id, err := result.LastInsertId()
	if err != nil || id <= 50 {
		t.Fatalf("autoincrement was reset: %d %v", id, err)
	}
}
