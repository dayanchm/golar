func TestCompilerDialects(t *testing.T) {
	for _, dialect := range []string{"sqlite", "postgres", "mysql"} {
		t.Run(dialect, func(t *testing.T) {
			b := &schema.Blueprint{Table: "users"}
			b.ID()
			b.String("email", 255).Unique()
			b.Boolean("active").Default(true)
			b.Decimal("amount", 10, 2)
			b.JSON("metadata").Nullable()
			b.UUID("uuid")
			b.Binary("data")
			b.ForeignID("team_id").Constrained("teams").CascadeOnDelete()
			b.Index("email", "active")
			b.Timestamps()
			b.SoftDeletes()
			compiler, err := schema.NewCompiler(dialect)
			if err != nil {
				t.Fatal(err)
			}
			sql, err := compiler.CompileCreate(b)
			if err != nil {
				t.Fatal(err)
			}
			joined := strings.Join(sql, "\n")
			for _, want := range []string{"PRIMARY KEY", "UNIQUE", "FOREIGN KEY", "ON DELETE CASCADE", "CREATE INDEX"} {
				if !strings.Contains(joined, want) {
					t.Errorf("missing %s in %s", want, joined)
				}
			}
			if dialect == "sqlite" && !strings.Contains(joined, "AUTOINCREMENT") {
				t.Fatal(joined)
			}
			if dialect == "postgres" && !strings.Contains(joined, "GENERATED BY DEFAULT AS IDENTITY") {
				t.Fatal(joined)
			}
			if dialect == "mysql" && !strings.Contains(joined, "AUTO_INCREMENT") {
				t.Fatal(joined)
			}
		})
	}
}
